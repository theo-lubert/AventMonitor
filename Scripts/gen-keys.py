#!/usr/bin/env python3
"""Generate Core/keys_gen.go from aventproxy's const.py without importing it.

  gen-keys.py <const.py> <out.go>
"""
import ast
import sys

src, out = sys.argv[1:3]
values = {}
for node in ast.parse(open(src).read()).body:
    if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
        name = node.targets[0].id
        if name in ("TUYA_SIGNING_KEY", "TUYA_APP_KEY"):
            values[name] = ast.literal_eval(node.value)
missing = {"TUYA_SIGNING_KEY", "TUYA_APP_KEY"} - values.keys()
if missing:
    sys.exit(f"missing in {src}: {', '.join(sorted(missing))}")
with open(out, "w") as f:
    f.write("// Code generated by Scripts/gen-keys.py from aventproxy's const.py. DO NOT EDIT.\n\n")
    f.write("package main\n\n")
    f.write(f"const signingKey = {values['TUYA_SIGNING_KEY']!r}\n".replace("'", '"'))
    f.write(f"const appKey = {values['TUYA_APP_KEY']!r}\n".replace("'", '"'))
